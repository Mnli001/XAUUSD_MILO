/*
 * The one-click Windows installer for the MT5 robot: a .bat file that unpacks the PowerShell script after its
 * marker line to %TEMP% and runs it. The script finds the member's MT5 terminals, puts XauBot.ex5 into the chosen
 * one, writes the robot's inputs (sync address, token, Transport = AUTO) as a preset, installs and starts the file
 * bridge helper, and starts MT5 with a startup config that opens a gold chart with the robot on it.
 *
 * The gold symbol is the one of the server the terminal logs in to (config\common.ini [Common] Server=), read from
 * that server's bases\<server>\history and \ticks folders only: brokers name gold differently (XAUUSD, XAUUSD.m,
 * GOLD…) and a symbol of another broker makes MT5 drop the robot ("symbol synchronization timeout"). When no gold
 * symbol is found for sure the script does not guess: MT5 starts without a chart and the member is told how to
 * put the robot on the gold chart by hand.
 *
 * What MT5 does not let it do: allow the site's address for WebRequest. MT5 keeps that list encrypted in common.ini,
 * and a startup config's [Experts] has no key for it (tried on a test terminal, build 6230: common.ini stayed byte
 * for byte the same). So the robot (Transport = AUTO, v3.93+) falls back to a FILE BRIDGE when WebRequest answers
 * 4014: it writes Common\Files\xaubot\<login>_<magic>_<symbol>\request.json (one folder per chart) and reads response.json, and a small helper the script
 * installs (%LOCALAPPDATA%\XauBot\bridge.ps1, started hidden at sign-in by bridge.vbs in the Startup folder, no admin)
 * posts each request to the site and writes the answer back. The member has nothing to paste.
 *
 * Everything here is pure: the route passes the origin, sync address and token in.
 */

export const INSTALLER_FILENAME = "XauBot-Setup.bat";
/** The line in the .bat after which the PowerShell script starts. */
export const PS_MARKER = "#XAUBOT-PS1";
export const EXPERT_NAME = "XauBot";
export const PRESET_FILE = "XauBot.set";
export const STARTUP_INI = "xaubot-start.ini";
/** Stands for the gold symbol in the startup config until the script has found the terminal's own name for it. */
export const GOLD_PLACEHOLDER = "__GOLD__";

export type InstallerInput = { origin: string; syncUrl: string; token: string };

const CRLF = "\r\n";
export const toCrlf = (s: string) => s.replace(/\r?\n/g, CRLF);

/** A PowerShell single-quoted literal: nothing inside is expanded, a quote is written twice. */
export function psStr(s: string): string {
  if ([...s].some((c) => c.charCodeAt(0) < 0x20 || c.charCodeAt(0) === 0x7f)) throw new Error("installer: a value may not hold control characters");
  return `'${s.replaceAll("'", "''")}'`;
}

function checked({ origin, syncUrl, token }: InstallerInput): InstallerInput {
  const o = origin.replace(/\/+$/, "");
  if (!/^https?:\/\/[^\s/'"]+$/.test(o)) throw new Error("installer: the origin must be a bare http(s) address");
  if (!/^https?:\/\/\S+$/.test(syncUrl)) throw new Error("installer: the sync address must be an http(s) address");
  if (!/^[A-Za-z0-9_-]{16,128}$/.test(token)) throw new Error("installer: unexpected token format");
  return { origin: o, syncUrl, token };
}

/**
 * MQL5\Presets\XauBot.set: the inputs the installer sets. Every other input keeps the robot's default. Transport is
 * an enum, which a .set file holds as its number: 0 = TRANSPORT_AUTO (WebRequest, else the file bridge).
 */
export function presetLines(syncUrl: string, token: string): string[] {
  return [`ServerUrl=${syncUrl}`, `BotToken=${token}`, "Transport=0"];
}
export const presetText = (syncUrl: string, token: string) => presetLines(syncUrl, token).join(CRLF) + CRLF;

/**
 * The startup config MT5 is launched with (terminal64.exe /config:"…"). Without a symbol it only switches algo
 * trading on and opens no chart: the robot is then put on the gold chart by hand.
 */
export function startupIniLines(symbol?: string): string[] {
  const experts = ["[Experts]", "Enabled=1", "AllowLiveTrading=1", "AllowDllImport=0"];
  if (!symbol) return experts;
  return [
    ...experts,
    "[StartUp]",
    `Expert=${EXPERT_NAME}`,
    `ExpertParameters=${PRESET_FILE}`,
    `Symbol=${symbol}`,
    "Period=M15",
  ];
}
export const startupIniText = (symbol?: string) => startupIniLines(symbol).join(CRLF) + CRLF;

/* ---- The file bridge helper ---- */

export const BRIDGE_DIR = "XauBot"; // under %LOCALAPPDATA%
export const BRIDGE_PS1 = "bridge.ps1";
export const BRIDGE_VBS = "bridge.vbs";
export const BRIDGE_LOG = "bridge.log";
export const BRIDGE_MUTEX = "Local\\XauBotBridge";
/** Stands for the full path of bridge.ps1 in bridge.vbs until the script knows where %LOCALAPPDATA% is. */
export const BRIDGE_PATH_PLACEHOLDER = "__BRIDGE_PS1__";

/**
 * bridge.ps1 (Windows PowerShell 5.1, ASCII only). Every 500 ms it looks at <CommonRoot>\Files\xaubot\*\request.json
 * ({"url","token","seq","at","body"} written by the robot); for a new seq it POSTs body to url with x-bot-token and
 * writes {"seq","status","body"} to response.json in the same folder (.tmp, then moved over), status 0 when the site
 * could not be reached. It only ever posts to this site (`origin`), so the token cannot be sent elsewhere by a file
 * some other program writes. One instance (named mutex); it exits when its own file is replaced, so a new install
 * takes over. -Once handles what is there now and stops (tests); -CommonRoot points it at another folder (tests).
 * The log (bridge.log next to the script, last 200 lines) never holds a token.
 */
export function bridgeScriptLines(origin: string): string[] {
  const o = origin.replace(/\/+$/, "");
  if (!/^https?:\/\/[^\s/'"]+$/.test(o)) throw new Error("bridge: the origin must be a bare http(s) address");
  return [
    "# XauBot bridge: carries the XauBot robot's reports from MetaTrader 5 to the site and the answers back, for an MT5",
    "# whose WebRequest list does not hold the site's address. Installed by XauBot-Setup.bat. To remove it: delete",
    "# bridge.vbs from the Startup folder (shell:startup) and the folder %LOCALAPPDATA%\\XauBot.",
    "param(",
    "  [string]$CommonRoot = (Join-Path $env:APPDATA 'MetaQuotes\\Terminal\\Common'),",
    "  [switch]$Once",
    ")",
    "$ErrorActionPreference = 'Stop'",
    "$ProgressPreference = 'SilentlyContinue'",
    "try { [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12 } catch {}",
    "",
    `$SiteOrigin = ${psStr(o)}`,
    `$MutexName = ${psStr(BRIDGE_MUTEX)}`,
    "$Self = $PSCommandPath",
    `$LogFile = Join-Path (Split-Path -Parent $Self) ${psStr(BRIDGE_LOG)}`,
    "$Utf8 = New-Object System.Text.UTF8Encoding($false)",
    "$MaxAge = 60        # seconds: an older request (MT5 closed long ago) is not sent",
    "",
    "if (-not $Once) {",
    "  $created = $false",
    "  $script:Mutex = New-Object System.Threading.Mutex($true, $MutexName, [ref]$created)",
    "  if (-not $created) { exit 0 }  # already running",
    "}",
    "",
    "$script:Log = New-Object System.Collections.Generic.List[string]",
    "try { if (Test-Path -LiteralPath $LogFile) { foreach ($l in @(Get-Content -LiteralPath $LogFile -Tail 199 -Encoding UTF8)) { $script:Log.Add([string]$l) } } } catch {}",
    "function Write-Log([string]$Text) {",
    "  $script:Log.Add((Get-Date -Format 'yyyy-MM-dd HH:mm:ss') + '  ' + $Text)",
    "  while ($script:Log.Count -gt 200) { $script:Log.RemoveAt(0) }",
    "  try { [System.IO.File]::WriteAllLines($LogFile, $script:Log.ToArray(), $Utf8) } catch {}",
    "}",
    "",
    "# A chart's folder is <login>_<magic>_<symbol>: only the login's last 4 digits are shown.",
    "function Get-Who([string]$Dir) {",
    "  $n = (Split-Path -Leaf $Dir).Split('_')[0]",
    "  if ($n.Length -gt 4) { return '...' + $n.Substring($n.Length - 4) }",
    "  return $n",
    "}",
    "",
    "# A file the robot may be rewriting right now: opened so as not to block it; $null when it cannot be read.",
    "function Read-Shared([string]$Path) {",
    "  try {",
    "    $fs = New-Object System.IO.FileStream($Path, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, ([System.IO.FileShare]::ReadWrite -bor [System.IO.FileShare]::Delete))",
    "    try { $sr = New-Object System.IO.StreamReader($fs, $Utf8, $true); return $sr.ReadToEnd() } finally { $fs.Dispose() }",
    "  } catch { return $null }",
    "}",
    "",
    "# A JSON string literal, ASCII only (anything else as \\uXXXX), as the robot reads it.",
    "$JsonEvaluator = [System.Text.RegularExpressions.MatchEvaluator]{",
    "  param($m)",
    "  $c = [int][char]$m.Value",
    "  if ($c -eq 0x22) { return '\\\"' }",
    "  if ($c -eq 0x5C) { return '\\\\' }",
    "  return ('\\u{0:x4}' -f $c)",
    "}",
    "function ConvertTo-JsonString([string]$s) {",
    "  if ($null -eq $s) { $s = '' }",
    "  return '\"' + [regex]::Replace($s, '[\\x00-\\x1f\"\\\\\\u007f-\\uffff]', $JsonEvaluator) + '\"'",
    "}",
    "",
    "function Send-Report([string]$Url, [string]$Token, [string]$Body) {",
    "  $r = @{ Status = 0; Body = ''; Error = '' }",
    "  $resp = $null",
    "  try {",
    "    $req = [System.Net.HttpWebRequest]::Create($Url)",
    "    $req.Method = 'POST'",
    "    $req.ContentType = 'application/json'",
    "    $req.Headers.Add('x-bot-token', $Token)",
    "    $req.Timeout = 10000",
    "    $req.ReadWriteTimeout = 10000",
    "    $req.UserAgent = 'XauBot-Bridge/1'",
    "    $bytes = $Utf8.GetBytes($Body)",
    "    $req.ContentLength = $bytes.Length",
    "    $s = $req.GetRequestStream()",
    "    try { $s.Write($bytes, 0, $bytes.Length) } finally { $s.Close() }",
    "    $resp = $req.GetResponse()",
    "  } catch {",
    "    $ex = $_.Exception",
    "    while ($ex -and -not ($ex -is [System.Net.WebException])) { $ex = $ex.InnerException }",
    "    if ($ex -and $ex.Response) { $resp = $ex.Response } else { $r.Error = $_.Exception.Message.Replace($Token, '***'); return $r }",
    "  }",
    "  try {",
    "    $r.Status = [int]$resp.StatusCode",
    "    $sr = New-Object System.IO.StreamReader($resp.GetResponseStream(), $Utf8)",
    "    try { $r.Body = $sr.ReadToEnd() } finally { $sr.Close() }",
    "  } catch { $r.Error = $_.Exception.Message.Replace($Token, '***') } finally { $resp.Close() }",
    "  return $r",
    "}",
    "",
    "function Write-Response([string]$Dir, $Seq, [int]$Status, [string]$Body) {",
    "  $json = '{\"seq\":' + $Seq + ',\"status\":' + $Status + ',\"body\":' + (ConvertTo-JsonString $Body) + '}'",
    "  $tmp = Join-Path $Dir 'response.tmp'",
    "  $dst = Join-Path $Dir 'response.json'",
    "  [System.IO.File]::WriteAllText($tmp, $json, $Utf8)",
    "  for ($i = 0; $i -lt 20; $i++) {",
    "    try { Move-Item -LiteralPath $tmp -Destination $dst -Force; return } catch { Start-Sleep -Milliseconds 50 }  # the robot may be reading it",
    "  }",
    "}",
    "",
    "$script:Seen = @{}   # folder -> last request handled (seq|at)",
    "$script:Stamp = @{}  # folder -> request.json time and size, so an unchanged file is not read again",
    "$script:Said = @{}   # folder -> last outcome logged",
    "",
    "function Invoke-Folder([string]$Dir) {",
    "  $file = Join-Path $Dir 'request.json'",
    "  $info = New-Object System.IO.FileInfo($file)",
    "  if (-not $info.Exists) { return }",
    "  $stamp = [string]$info.LastWriteTimeUtc.Ticks + '/' + [string]$info.Length",
    "  if ($script:Stamp[$Dir] -eq $stamp) { return }",
    "  $text = Read-Shared $file",
    "  if (-not $text) { return }",
    "  try { $req = $text | ConvertFrom-Json } catch { return }  # half written: looked at again next time",
    "  if ($null -eq $req -or $null -eq $req.seq -or $null -eq $req.body -or -not $req.url) { return }",
    "  $script:Stamp[$Dir] = $stamp",
    "  $key = [string]$req.seq + '|' + [string]$req.at",
    "  if ($script:Seen[$Dir] -eq $key) { return }",
    "  $script:Seen[$Dir] = $key",
    "  $now = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()",
    "  if ($req.at -and ([long]$req.at -lt $now - $MaxAge)) { return }",
    "  $url = [string]$req.url",
    "  $token = [string]$req.token",
    "  if (-not $url.StartsWith($SiteOrigin + '/', [System.StringComparison]::OrdinalIgnoreCase)) {",
    "    $r = @{ Status = 0; Body = ''; Error = ('the address is not this site''s: ' + $url) }",
    "  } else {",
    "    $r = Send-Report $url $token ([string]$req.body)",
    "  }",
    "  Write-Response $Dir $req.seq $r.Status $r.Body",
    "  $outcome = 'status ' + $r.Status",
    "  if ($r.Error) { $outcome += ' (' + $r.Error + ')' }",
    "  if ($script:Said[$Dir] -ne $outcome) {",
    "    $script:Said[$Dir] = $outcome",
    "    Write-Log ((Get-Who $Dir) + ': ' + $outcome)",
    "  }",
    "}",
    "",
    "function Invoke-Scan {",
    "  $root = Join-Path $CommonRoot 'Files\\xaubot'",
    "  if (-not [System.IO.Directory]::Exists($root)) { return }",
    "  foreach ($d in [System.IO.Directory]::GetDirectories($root)) {",
    "    try { Invoke-Folder $d } catch { Write-Log ((Get-Who $d) + ': ' + $_.Exception.Message) }",
    "  }",
    "}",
    "",
    "if ($Once) { Invoke-Scan; exit 0 }",
    "",
    "Write-Log ('started, site ' + $SiteOrigin)",
    "$selfTime = (Get-Item -LiteralPath $Self).LastWriteTimeUtc",
    "$tick = 0",
    "while ($true) {",
    "  try { Invoke-Scan } catch { Write-Log $_.Exception.Message }",
    "  $tick++",
    "  if ($tick % 20 -eq 0) {  # every 10 s: a new install replaced this file, so make way for the new one",
    "    try { if ((Get-Item -LiteralPath $Self).LastWriteTimeUtc -ne $selfTime) { Write-Log 'replaced by a new install, stopping'; break } } catch {}",
    "  }",
    "  Start-Sleep -Milliseconds 500",
    "}",
    "try { $script:Mutex.ReleaseMutex() } catch {}",
    "exit 0",
  ];
}
export const bridgeScript = (origin: string) => bridgeScriptLines(origin).join(CRLF) + CRLF;

